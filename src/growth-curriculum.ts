const byId = new Map(GROWTH_CURRICULUM.lessons.map((x) => [x.id, x]))

export function findLesson(id: string): Lesson | undefined {
  return byId.get(String(id ?? ''))
}

/** id 精确优先；否则按标题/标签模糊找（最多 3 条，供 Agent 选课）。 */
export function lessonByQuery(q: string): Lesson[] {
  const s = String(q ?? '').trim().toLowerCase()
  if (!s) return []
  const exact = byId.get(s)
  if (exact) return [exact]
  const hits = GROWTH_CURRICULUM.lessons.filter(
    (x) => x.title.toLowerCase().includes(s) || x.id.includes(s) || x.tags.some((t) => t.toLowerCase().includes(s)),
  )
  return hits.slice(0, 3)
}
